export type FigureInsertMode = 'tikz_package' | 'external_graphic';
export type FigureColumnSpan = 'single_column' | 'double_column';

export interface InsertFigureSnippetOptions {
  mode: FigureInsertMode;
  relativePath?: string; // e.g., "figures/fig1-architecture.tikz" or "figures/external/overview.pdf"
  figureRelPath?: string;
  span?: FigureColumnSpan;
  columnSpan?: FigureColumnSpan;
  widthRatio?: string | number; // e.g. "1.0" or "0.95"
  caption: string;
  label: string;
  placement?: string; // e.g. "t", "htbp"
}

/**
 * Builds the clean LaTeX `\begin{figure}...\end{figure}` or `\begin{figure*}...\end{figure*}`
 * snippet for inserting a TikZ code package (`\input{figures/xxx.tikz}`) or external graphic.
 */
export function buildFigureLaTeXSnippet(
  opts: InsertFigureSnippetOptions
): string {
  validateFigureOptions(opts);
  const effectiveSpan = opts.span || opts.columnSpan || 'single_column';
  const env = effectiveSpan === 'double_column' ? 'figure*' : 'figure';
  const placement = opts.placement || 't';
  const baseWidthCmd =
    effectiveSpan === 'double_column' ? '\\textwidth' : '\\columnwidth';
  const ratioStr =
    opts.widthRatio !== undefined ? String(Number(opts.widthRatio)) : '';
  const ratio =
    ratioStr && ratioStr !== '1' && ratioStr !== '1.0' ? ratioStr : '';
  const widthExpr = `${ratio}${baseWidthCmd}`;
  const cleanRel = figurePathArgument(opts.relativePath || opts.figureRelPath || '');

  const bodyLine =
    opts.mode === 'tikz_package'
      ? `  \\resizebox{${widthExpr}}{!}{\\input{${cleanRel}}}`
      : `  \\includegraphics[width=${widthExpr}]{${cleanRel}}`;

  return [
    `\\begin{${env}}[${placement}]`,
    '  \\centering',
    bodyLine,
    `  \\caption{${opts.caption}}`,
    `  \\label{${opts.label || 'fig:figure'}}`,
    `\\end{${env}}`,
  ].join('\n');
}

