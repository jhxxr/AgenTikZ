/**
 * Generates `styles/agentikz-macros.sty` containing all journal color tokens
 * and canonical TikZ node styles so `\input{figures/xxx.tikz}` compiles cleanly
 * inside any paper without polluting `main.tex`.
 */
export function generateAgentikzMacrosSty(_activeThemeId?: JournalThemeId): string {
  const colorLines: string[] = [];
  const seenColors = new Set<string>();

  for (const theme of Object.values(JOURNAL_THEMES)) {
    colorLines.push(`% --- ${theme.name} (${theme.id}) ---`);
    for (const tok of theme.palette) {
      const baseName = tok.name;
      const strokeHex = tok.strokeHex.replace('#', '').toUpperCase();
      if (!seenColors.has(baseName)) {
        seenColors.add(baseName);
        colorLines.push(`\\definecolor{${baseName}}{HTML}{${strokeHex}}`);
      }
      const fillHex = tok.fillHex.replace('#', '').toUpperCase();
      const fillAlias = `${tok.name}_fill`;
      if (!seenColors.has(fillAlias)) {
        seenColors.add(fillAlias);
        colorLines.push(`\\definecolor{${fillAlias}}{HTML}{${fillHex}}`);
      }
    }
  }

  return [
    '%% ============================================================================',
    '%% styles/agentikz-macros.sty',
    '%% Auto-generated by AgenTikZ Studio — Scientific Figure & Paper IDE',
    '%% Provides TikZ libraries, PGFPlots settings, Journal Color Palettes, and',
    '%% canonical neural/scientific node styles for \\input{figures/*.tikz}.',
    '%% ============================================================================',
    '\\NeedsTeXFormat{LaTeX2e}',
    '\\ProvidesPackage{styles/agentikz-macros}[2026/11/07 AgenTikZ Scientific Figure Macros]',
    '',
    '\\RequirePackage{tikz}',
    '\\RequirePackage{pgfplots}',
    '\\RequirePackage{graphicx}',
    '\\RequirePackage{amsmath,amssymb}',
    '\\RequirePackage{booktabs}',
    '\\pgfplotsset{compat=1.18}',
    '\\usetikzlibrary{arrows.meta,positioning,calc,fit,backgrounds,shapes.geometric,decorations.pathreplacing}',
    '',
    '%% --- Publication Color Tokens (Nature NPG / NeurIPS / CVPR / IEEE) ---',
    ...colorLines,
    '',
    '%% --- Canonical AgenTikZ Node & Routing Styles ---',
    '\\tikzset{',
    '  dl_block/.style={rectangle, rounded corners=2.5pt, minimum width=2.8cm, minimum height=0.82cm, align=center, line width=0.65pt, font=\\small},',
    '  module/.style={dl_block},',
    '  mha_block/.style={rectangle, rounded corners=2.5pt, minimum width=3.2cm, minimum height=0.85cm, align=center, line width=0.75pt, font=\\small\\bfseries},',
    '  addnorm_block/.style={rectangle, rounded corners=2pt, minimum width=3.0cm, minimum height=0.68cm, align=center, line width=0.6pt, font=\\scriptsize},',
    '  op_circle/.style={circle, minimum size=0.58cm, inner sep=0pt, align=center, line width=0.65pt, fill=white, draw=black!70, font=\\small},',
    '  stage_box/.style={rectangle, rounded corners=4pt, dashed, line width=0.7pt, inner sep=8pt, align=center},',
    '  feature_cube/.style={rectangle, rounded corners=1.5pt, minimum width=1.1cm, minimum height=1.5cm, align=center, line width=0.65pt, font=\\scriptsize},',
    '  flow/.style={-Latex, line width=0.65pt},',
    '}',
    '\\endinput',
    '',
  ].join('\n');
}

